import { ComponentFixture, TestBed } from '@angular/core/testing';
import { MAT_DIALOG_DATA, MatDialogRef } from '@angular/material/dialog';
import { NoopAnimationsModule } from '@angular/platform-browser/animations';
import { of } from 'rxjs';
import { AdminService } from '../../services/admin.service';
import { SetupLinkDialogComponent, SetupLinkDialogData } from './setup-link-dialog.component';

/**
 * The dialog an administrator sees after approving an access request. It
 * shows the setup link and says whether the requester was emailed it.
 */
describe('SetupLinkDialogComponent', () => {
  let fixture: ComponentFixture<SetupLinkDialogComponent>;
  let adminService: jasmine.SpyObj<AdminService>;

  const BASE: SetupLinkDialogData = {
    userId: 7,
    userName: 'New Comer',
    userEmail: 'newcomer@acme.test',
    setupUrl: 'https://app.example.test/acme.test/setup?token=first',
    expiresInHours: 48
  };

  async function open(data: SetupLinkDialogData): Promise<void> {
    adminService = jasmine.createSpyObj<AdminService>('AdminService', ['sendSetupEmail']);
    await TestBed.configureTestingModule({
      imports: [SetupLinkDialogComponent, NoopAnimationsModule],
      providers: [
        { provide: MAT_DIALOG_DATA, useValue: { ...data } },
        { provide: MatDialogRef, useValue: { close: () => undefined } },
        { provide: AdminService, useValue: adminService }
      ]
    }).compileComponents();

    fixture = TestBed.createComponent(SetupLinkDialogComponent);
    fixture.detectChanges();
  }

  function text(testId: string): string | null {
    const element = fixture.nativeElement.querySelector(`[data-testid="${testId}"]`);
    return element ? element.textContent.replace(/\s+/g, ' ').trim() : null;
  }

  it('says the link was emailed and still shows it', async () => {
    await open({ ...BASE, emailSent: true, deliveryMessage: 'The setup link was emailed to newcomer@acme.test.' });

    expect(text('delivery-message')).toContain('The setup link was emailed to newcomer@acme.test.');
    expect(fixture.nativeElement.querySelector('[data-testid="delivery-message"]').classList)
      .not.toContain('delivery-failed');
    expect(text('setup-link-instruction')).toBe(
      'You can also copy the link and send it yourself. The link expires in 48 hours.'
    );
    expect(text('send-setup-email')).toContain('Send again');
    expect(fixture.nativeElement.querySelector('input').value).toBe(BASE.setupUrl);
  });

  it('tells the administrator to pass the link on when no email was sent', async () => {
    const message = 'Email is not set up, so no email was sent. Give this link to newcomer@acme.test yourself.';
    await open({ ...BASE, emailSent: false, deliveryMessage: message });

    expect(text('delivery-message')).toContain(message);
    expect(fixture.nativeElement.querySelector('[data-testid="delivery-message"]').classList)
      .toContain('delivery-failed');
    expect(text('setup-link-instruction')).toContain('Share this setup link with the user');
    expect(text('send-setup-email')).toContain('Send Email');
  });

  it('shows no delivery line for a link the administrator generated by hand', async () => {
    await open(BASE);

    expect(text('delivery-message')).toBeNull();
    expect(text('setup-link-instruction')).toContain('Share this setup link with the user');
  });

  it('shows the new link after sending, because sending ends the old one', async () => {
    await open(BASE);
    adminService.sendSetupEmail.and.returnValue(of({
      message: 'Setup email sent successfully to newcomer@acme.test',
      setup_url: 'https://app.example.test/acme.test/setup?token=second',
      expires_at: '2026-11-24T00:00:00',
      hours_valid: 48
    }));

    fixture.componentInstance.sendEmail();
    fixture.detectChanges();

    expect(adminService.sendSetupEmail).toHaveBeenCalledOnceWith(7);
    expect(fixture.componentInstance.data.setupUrl).toBe('https://app.example.test/acme.test/setup?token=second');
    expect(fixture.componentInstance.emailSent).toBeTrue();
  });
});
